async def seed_knowledge(skip_if_populated: bool = False):
    async with AsyncSessionLocal() as db:
        if skip_if_populated:
            count_result = await db.execute(select(func.count()).select_from(Advice))
            existing = count_result.scalar() or 0
            if existing > 0:
                print(f"Knowledge base already has {existing} items — skipping seed.")
                return

        # Удалить все существующие советы и вставить актуальные
        await db.execute(delete(Advice))
        await db.flush()

        for item in KNOWLEDGE:
            advice = Advice(
                title=item["title"],
                content=item["content"],
                steps=item["steps"],
                room_names=item["room_names"],
                task_keywords=item["task_keywords"],
                season=item.get("season"),
                category=item.get("category", "regular"),
                is_active=True,
            )
            db.add(advice)

        await db.commit()
        print(f"✅ Knowledge base seeded: {len(KNOWLEDGE)} advice items")


if __name__ == "__main__":
    # python -m app.seed_knowledge           → force re-seed (delete all + reinsert)
    # python -m app.seed_knowledge --if-empty → skip if advice table already has data
    skip_if_populated = "--if-empty" in sys.argv
    asyncio.run(seed_knowledge(skip_if_populated=skip_if_populated))
